import 'package:latlong2/latlong.dart';

/// Digos City barangay boundaries from the standalone `map/` project
/// (`map/lib/data/digos_geodata.dart`): 75 shared topological arcs that stitch
/// into all 26 barangays plus the outer city perimeter. Keeping the shared arcs
/// means an internal border is drawn once, so neighbouring barangays cannot
/// disagree about where the line is.
class BarangayFeature {
  final int id;
  final String psgcCode;
  final String name;
  final List<LatLng> ring;
  final LatLng centroid;

  const BarangayFeature({
    required this.id,
    required this.psgcCode,
    required this.name,
    required this.ring,
    required this.centroid,
  });
}

class DigosGeoData {
  /// Outer Digos City perimeter, stitched from the same shared arcs as the
  /// barangays. Wound clockwise for the inverse mask's hole.
  static final List<LatLng> cityRing = stitchRing(cityArcs);

  /// Convert pixel coordinate [x, y] to LatLng(lat, lon)
  static LatLng toLatLng(List<int> pt) {
    final double lon = double.parse(
      (125.2709 + (pt[0] - 331) * 0.00005639).toStringAsFixed(5),
    );
    final double lat = double.parse(
      (6.9874 - (pt[1] - 4) * 0.00005660).toStringAsFixed(5),
    );
    return LatLng(lat, lon);
  }

  /// Assemble a closed polygon ring of LatLng coordinates from shared arc indices
  static List<LatLng> stitchRing(List<int> arcIndices) {
    final List<LatLng> coords = [];
    for (final int idx in arcIndices) {
      final List<List<int>> rawArc = idx >= 0
          ? arcs[idx]
          : arcs[~idx].reversed.toList();
      for (int i = 0; i < rawArc.length - 1; i++) {
        coords.add(toLatLng(rawArc[i]));
      }
    }
    if (coords.isNotEmpty) {
      coords.add(coords.first);
    }
    return coords;
  }

  /// Compute area-weighted polygon centroid for placing barangay labels
  static LatLng computeCentroid(List<LatLng> ring) {
    if (ring.isEmpty) return const LatLng(6.84, 125.33);
    double area = 0.0;
    double cx = 0.0;
    double cy = 0.0;

    for (int i = 0; i < ring.length - 1; i++) {
      final double x0 = ring[i].longitude;
      final double y0 = ring[i].latitude;
      final double x1 = ring[i + 1].longitude;
      final double y1 = ring[i + 1].latitude;
      final double cross = x0 * y1 - x1 * y0;
      area += cross;
      cx += (x0 + x1) * cross;
      cy += (y0 + y1) * cross;
    }

    area *= 0.5;
    if (area.abs() < 1e-12) {
      double sumLat = 0, sumLon = 0;
      for (final p in ring) {
        sumLat += p.latitude;
        sumLon += p.longitude;
      }
      return LatLng(sumLat / ring.length, sumLon / ring.length);
    }

    cx /= (6.0 * area);
    cy /= (6.0 * area);
    return LatLng(cy, cx);
  }

  /// Ray-casting point-in-polygon check for tap/hover detection
  static bool isPointInPolygon(LatLng point, List<LatLng> polygon) {
    bool inside = false;
    final double x = point.longitude;
    final double y = point.latitude;

    for (int i = 0, j = polygon.length - 1; i < polygon.length; j = i++) {
      final double xi = polygon[i].longitude;
      final double yi = polygon[i].latitude;
      final double xj = polygon[j].longitude;
      final double yj = polygon[j].latitude;

      final bool intersect =
          ((yi > y) != (yj > y)) &&
          (x <
              (xj - xi) * (y - yi) / ((yj - yi) == 0 ? 1e-15 : (yj - yi)) + xi);
      if (intersect) inside = !inside;
    }
    return inside;
  }

  /// Build all 26 Barangay features
  static List<BarangayFeature> buildBarangays() {
    final List<BarangayFeature> features = [];
    for (int i = 0; i < brgys.length; i++) {
      final (String name, List<int> arcIndices) = brgys[i];
      final List<LatLng> ring = stitchRing(arcIndices);
      features.add(
        BarangayFeature(
          id: i + 1,
          psgcCode: '${i + 1}',
          name: name,
          ring: ring,
          centroid: computeCentroid(ring),
        ),
      );
    }
    return features;
  }

